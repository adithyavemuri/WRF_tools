"""Discover the package's public function surface without importing optional tools.

The catalog is also the allowlist used by run-recipe. It prevents public
algorithms quietly disappearing from the user-facing entry point.
"""
from __future__ import annotations

import ast
from importlib import import_module
from functools import lru_cache
from copy import deepcopy
from pathlib import Path
from .methods import _basis

_CONTROL_MODULES = {"cli", "capabilities", "recipes"}


@lru_cache(maxsize=1)
def _catalog_entries():
    """Return every public top-level function, signature, docstring and source.

    Private helpers, dataclass methods and CLI/catalog orchestration are excluded.
    Source modules give unambiguous IDs even when facades re-export a function.
    A catalog entry establishes availability, not scientific validation.
    """
    root = Path(__file__).parent
    result = {}
    for path in sorted(root.rglob("*.py")):
        module = ".".join(path.relative_to(root).with_suffix("").parts)
        if path.name == "__init__.py" or module in _CONTROL_MODULES:
            continue
        for node in ast.parse(path.read_text(encoding="utf-8")).body:
            if not isinstance(node, ast.FunctionDef) or node.name.startswith("_"):
                continue
            identity = f"{module}.{node.name}"
            result[identity] = dict(id=identity, module=module, name=node.name,
                signature=f"{node.name}({ast.unparse(node.args)})",
                documentation=ast.get_docstring(node) or "No function docstring; inspect the source and method ledger.",
                source=f"src/wrf_tools/{path.relative_to(root).as_posix()}", line=node.lineno,
                basis=_basis(module,node.name),
                external_action=node.name in {"run_openfast", "setup_map_data", "add_cached_features", "create_hindcast_report",
                                              "create_wind_animation", "export_contour_sequence"})
    return result


def capability_catalog():
    """Return the complete callable index and method basis (independent copy).

    Source discovery is cached per process; start a fresh process after editing
    package source. Changing a returned record cannot mutate the resolver.
    """
    return deepcopy(_catalog_entries())


def get_capability(identity):
    """Resolve a cataloged WRF_tools function only; no arbitrary module imports."""
    record = _catalog_entries().get(identity)
    if record is None:
        raise ValueError(f"Unknown capability {identity!r}; use wrf-tools capabilities")
    return getattr(import_module("wrf_tools."+record["module"]), record["name"])


def write_capability_guide(path):
    """Generate the complete API/recipe index, keeping documentation in sync."""
    lines = ["# Complete callable capability index", "",
        "Generated by `wrf-tools capabilities --markdown docs/API_CATALOG.md`.",
        "Every function below is directly callable by `wrf-tools run-recipe`.",
        "This is an execution/discovery index, not a claim of scientific validation.",
        "Private helpers and orchestration entry points are deliberately excluded.",
        "See [connected workflows](CONNECTED_WORKFLOWS.md) for editable recipes and report groups.", ""]
    previous = None
    for record in capability_catalog().values():
        if record["module"] != previous:
            lines.extend(["## "+record["module"], ""]); previous = record["module"]
        lines.extend([f"### `{record['id']}`", "", "```python", record["signature"], "```", "",
                      record["documentation"], "",
                      f"Source: [{record['source']}](../{record['source']}).", ""])
        basis=record["basis"]
        lines.extend([f"Method category: {basis['category']}. {basis['caveat']}","",
            "References/conventions: "+"; ".join(f"[{r['title']}]({r['url']})" for r in basis["references"])+".",""])
    path = Path(path); path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    return path
